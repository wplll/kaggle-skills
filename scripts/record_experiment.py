"""Append-only experiment ledger for Kaggle leaderboard runs.

Subcommands:
  add      append a new experiment entry
  update   append an overlay entry that updates a previous experiment
  list     tabulate experiments
  show     dump a single experiment's merged state
  report   render experiments.md summary

Storage layout under <root>/<competition>/:
  experiments.jsonl  append-only event log (one JSON object per line)
  experiments.md     rendered summary (regenerated by `report`)

Each event has:
  id              str   exp-NNN, assigned by `add`
  ts              str   ISO timestamp
  op              str   "add" | "update"
  fields          dict  free-form payload (phase, kernel, version, code_delta,
                        metadata_delta, validation_markers, status, public_score,
                        failure_mode, decision, notes, tags)
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


KNOWN_FIELDS = (
    "phase",
    "kernel",
    "version",
    "code_delta",
    "metadata_delta",
    "validation_markers",
    "status",
    "public_score",
    "private_score",
    "failure_mode",
    "decision",
    "notes",
    "tags",
)


def now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def ledger_path(root: Path, competition: str) -> Path:
    return root / competition / "experiments.jsonl"


def report_path(root: Path, competition: str) -> Path:
    return root / competition / "experiments.md"


def read_events(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    events: list[dict[str, Any]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            events.append(json.loads(line))
        except json.JSONDecodeError as exc:
            raise SystemExit(f"corrupt ledger line: {line!r} ({exc})")
    return events


def append_event(path: Path, event: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(event, ensure_ascii=False) + "\n")


def next_experiment_id(events: list[dict[str, Any]]) -> str:
    used: set[int] = set()
    for event in events:
        exp_id = str(event.get("id", ""))
        if exp_id.startswith("exp-"):
            try:
                used.add(int(exp_id[4:]))
            except ValueError:
                continue
    n = 1
    while n in used:
        n += 1
    return f"exp-{n:03d}"


def merge_experiment(events: list[dict[str, Any]], exp_id: str) -> dict[str, Any] | None:
    merged: dict[str, Any] | None = None
    history: list[dict[str, Any]] = []
    for event in events:
        if event.get("id") != exp_id:
            continue
        history.append(event)
        fields = event.get("fields", {}) or {}
        if merged is None:
            merged = {"id": exp_id, "created_at": event.get("ts"), **fields}
        else:
            merged.update(fields)
            merged["updated_at"] = event.get("ts")
    if merged is not None:
        merged["_history"] = history
    return merged


def all_experiments(events: list[dict[str, Any]]) -> list[dict[str, Any]]:
    seen: list[str] = []
    for event in events:
        exp_id = event.get("id")
        if isinstance(exp_id, str) and exp_id not in seen:
            seen.append(exp_id)
    return [merge_experiment(events, exp_id) for exp_id in seen if merge_experiment(events, exp_id) is not None]


def parse_kv(items: list[str]) -> dict[str, Any]:
    payload: dict[str, Any] = {}
    for item in items:
        if "=" not in item:
            raise SystemExit(f"--field expects key=value, got {item!r}")
        key, value = item.split("=", 1)
        key = key.strip()
        if not key:
            raise SystemExit(f"empty key in --field {item!r}")
        payload[key] = value
    return payload


def coerce_fields(args: argparse.Namespace) -> dict[str, Any]:
    fields: dict[str, Any] = {}
    for name in KNOWN_FIELDS:
        value = getattr(args, name, None)
        if value is not None:
            fields[name] = value
    fields.update(parse_kv(getattr(args, "field", []) or []))
    if "tags" in fields and isinstance(fields["tags"], str):
        fields["tags"] = [tag.strip() for tag in fields["tags"].split(",") if tag.strip()]
    return fields


def add_field_arguments(parser: argparse.ArgumentParser, *, required_phase: bool) -> None:
    parser.add_argument("--phase", required=required_phase, help="Phase label, e.g. P0, P1, P2")
    parser.add_argument("--kernel", help="<owner>/<slug>")
    parser.add_argument("--version", help="Kaggle kernel version")
    parser.add_argument("--code-delta", dest="code_delta")
    parser.add_argument("--metadata-delta", dest="metadata_delta")
    parser.add_argument("--validation-markers", dest="validation_markers")
    parser.add_argument("--status", help="QUEUED|RUNNING|COMPLETE|ERROR|SUBMITTED|FAILED")
    parser.add_argument("--public-score", dest="public_score")
    parser.add_argument("--private-score", dest="private_score")
    parser.add_argument("--failure-mode", dest="failure_mode")
    parser.add_argument("--decision", help="keep|drop|extend|rollback|hold")
    parser.add_argument("--notes")
    parser.add_argument("--tags", help="comma-separated tags")
    parser.add_argument(
        "--field",
        action="append",
        default=[],
        help="Extra free-form key=value (repeatable)",
    )


def cmd_add(args: argparse.Namespace) -> int:
    path = ledger_path(args.root, args.competition)
    events = read_events(path)
    fields = coerce_fields(args)
    if "phase" not in fields:
        raise SystemExit("--phase is required for add")
    exp_id = args.id or next_experiment_id(events)
    if any(event.get("id") == exp_id for event in events):
        raise SystemExit(f"id already exists: {exp_id}")
    event = {"id": exp_id, "ts": now_iso(), "op": "add", "fields": fields}
    append_event(path, event)
    print(f"added {exp_id} -> {path}")
    return 0


def cmd_update(args: argparse.Namespace) -> int:
    path = ledger_path(args.root, args.competition)
    events = read_events(path)
    if not any(event.get("id") == args.id for event in events):
        raise SystemExit(f"unknown experiment id: {args.id}")
    fields = coerce_fields(args)
    if not fields:
        raise SystemExit("update requires at least one --<field> or --field key=value")
    event = {"id": args.id, "ts": now_iso(), "op": "update", "fields": fields}
    append_event(path, event)
    print(f"updated {args.id} -> {path}")
    return 0


def truncate(value: Any, width: int) -> str:
    text = "" if value is None else str(value)
    text = text.replace("\n", " ").replace("|", "\\|")
    if len(text) <= width:
        return text
    return text[: max(0, width - 1)] + "..."


def cmd_list(args: argparse.Namespace) -> int:
    events = read_events(ledger_path(args.root, args.competition))
    rows = all_experiments(events)
    if args.phase:
        rows = [row for row in rows if row.get("phase") == args.phase]
    if not rows:
        print("(no experiments)")
        return 0
    headers = ("id", "phase", "kernel", "version", "status", "public_score", "decision")
    widths = (8, 6, 36, 8, 12, 14, 12)
    print(" ".join(h.ljust(w) for h, w in zip(headers, widths)))
    print(" ".join("-" * w for w in widths))
    for row in rows:
        cells = [truncate(row.get(field), width) for field, width in zip(headers, widths)]
        print(" ".join(cell.ljust(width) for cell, width in zip(cells, widths)))
    return 0


def cmd_show(args: argparse.Namespace) -> int:
    events = read_events(ledger_path(args.root, args.competition))
    merged = merge_experiment(events, args.id)
    if merged is None:
        raise SystemExit(f"unknown experiment id: {args.id}")
    history = merged.pop("_history", [])
    print(json.dumps(merged, indent=2, ensure_ascii=False))
    print("\n# history")
    for event in history:
        print(json.dumps(event, ensure_ascii=False))
    return 0


def render_report(competition: str, rows: list[dict[str, Any]]) -> str:
    timestamp = now_iso()
    lines = [
        f"# Experiment Ledger: {competition}",
        "",
        f"Generated at: {timestamp}",
        "",
        f"Total experiments: {len(rows)}",
        "",
        "## Summary Table",
        "",
        "| id | phase | kernel | version | status | publicScore | decision | failure |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            "| {id} | {phase} | {kernel} | {version} | {status} | {public_score} | {decision} | {failure_mode} |".format(
                id=truncate(row.get("id"), 12),
                phase=truncate(row.get("phase"), 8),
                kernel=truncate(row.get("kernel"), 60),
                version=truncate(row.get("version"), 8),
                status=truncate(row.get("status"), 14),
                public_score=truncate(row.get("public_score"), 14),
                decision=truncate(row.get("decision"), 14),
                failure_mode=truncate(row.get("failure_mode"), 40),
            )
        )
    lines.extend(["", "## Detail", ""])
    for row in rows:
        lines.append(f"### {row.get('id')} ({row.get('phase', '')})")
        lines.append("")
        lines.append(f"- created_at: {row.get('created_at', '')}")
        if row.get("updated_at"):
            lines.append(f"- updated_at: {row.get('updated_at')}")
        for field in KNOWN_FIELDS:
            if row.get(field) is None:
                continue
            value = row[field]
            if isinstance(value, list):
                value = ", ".join(str(item) for item in value)
            lines.append(f"- {field}: {value}")
        extras = {
            key: value
            for key, value in row.items()
            if key not in KNOWN_FIELDS and key not in {"id", "created_at", "updated_at", "_history"}
        }
        for key, value in extras.items():
            lines.append(f"- {key}: {value}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def cmd_report(args: argparse.Namespace) -> int:
    events = read_events(ledger_path(args.root, args.competition))
    rows = all_experiments(events)
    text = render_report(args.competition, rows)
    out = report_path(args.root, args.competition)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out} ({len(rows)} experiments)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=Path("research"), help="Research output root")
    parser.add_argument("--competition", required=True, help="Competition slug")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p_add = sub.add_parser("add", help="Append a new experiment")
    p_add.add_argument("--id", help="Override auto-assigned exp-NNN id")
    add_field_arguments(p_add, required_phase=True)
    p_add.set_defaults(func=cmd_add)

    p_update = sub.add_parser("update", help="Overlay an existing experiment")
    p_update.add_argument("--id", required=True)
    add_field_arguments(p_update, required_phase=False)
    p_update.set_defaults(func=cmd_update)

    p_list = sub.add_parser("list", help="Tabulate experiments")
    p_list.add_argument("--phase", help="Filter by phase label")
    p_list.set_defaults(func=cmd_list)

    p_show = sub.add_parser("show", help="Dump merged experiment with history")
    p_show.add_argument("id")
    p_show.set_defaults(func=cmd_show)

    p_report = sub.add_parser("report", help="Render experiments.md")
    p_report.set_defaults(func=cmd_report)

    args = parser.parse_args()
    return int(args.func(args))


if __name__ == "__main__":
    sys.exit(main())
